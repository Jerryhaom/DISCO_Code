args <- commandArgs(TRUE)
source(args[1])
checks <- list()
check <- function(name, value) {
  checks[[name]] <<- isTRUE(value)
  if (!isTRUE(value)) stop("Failed: ", name)
}
d <- function(x) as.Date(x)
base <- rep(d("2020-01-15"), 10)
death <- d(c("2020-01-20",NA,"2020-05-01",NA,"2020-05-01",NA,NA,NA,NA,NA))
loss <- d(c(NA,"2020-03-01","2020-03-01",NA,NA,NA,NA,NA,NA,NA))
diag <- d(c(NA,"2020-04-01",NA,"2020-01-10","2020-05-01","2020-01-15",
            "2020-01-16","2021-01-01","2020-12-31",NA))
run <- function(loss_rule="censor", same="prevalent", tie="exclude")
  build_day_endpoints(1:10,base,death,loss,diag,d("2020-12-31"),loss_rule,same,tie)
x <- run()
check("same-month positive death retained",x$mortality_days[1]==5 && x$mortality_event[1]==1)
check("nondead loss truncated",x$observation_end[2]==d("2020-03-01"))
check("death after loss is not event",x$mortality_event[3]==0 && x$mortality_days[3]==46)
check("same-month before baseline is prevalent",x$prevalent_disease[4])
check("prevalent is not incidence eligible",!x$eligible_incidence[4])
check("diagnosis after loss is not incident",x$incidence_event[2]==0 && x$diagnosis_after_end[2])
check("tie excluded explicitly",!x$eligible_incidence[5] && x$same_day_disease_death[5])
check("baseline-day prevalence explicit",x$prevalent_disease[6] && x$incidence_event[6]==0)
check("positive day incidence retained",x$incidence_days[7]==1 && x$incidence_event[7]==1)
check("after administrative cutoff rejected",x$incidence_event[8]==0 && x$diagnosis_after_end[8])
check("event on cutoff included",x$incidence_event[9]==1)
check("non-event censored at cutoff",x$incidence_event[10]==0 && x$observation_end[10]==d("2020-12-31"))
check("mortality uses days to years",max(abs(x$mortality_years-x$mortality_days/365.25))==0)
check("incidence uses days to years",max(abs(x$incidence_years-x$incidence_days/365.25))==0)
a <- run("ignore")
check("ignore loss only explicit",a$mortality_event[3]==1 && a$observation_end[2]==d("2020-12-31"))
b <- run(tie="disease_first")
check("disease first tie event",b$incidence_event[5]==1 && b$cif_event[5]==1)
c <- run(tie="death_first")
check("death first tie competing event",c$incidence_event[5]==0 && c$cif_event[5]==2)
e <- run(same="incident")
check("baseline incidence only explicit",e$incidence_event[6]==1 && e$incidence_days[6]==0)
z <- earliest_recorded_date(data.frame(a=d(c("2020-02-01",NA)),b=d(c("2019-12-31",NA))))
check("all cancer instances earliest, not instance zero",z[1]==d("2019-12-31"))
check("all missing diagnosis stays missing",is.na(z[2]))
fails <- function(expr) inherits(tryCatch(expr,error=function(e)e),"error")
check("missing cutoff rejected",fails(build_day_endpoints(1:10,base,death,loss,diag)))
check("ambiguous special date rejected",fails(endpoint_date(c("-1","2020-01-01"),"input")))
check("invalid calendar date rejected",fails(endpoint_date("2020-02-30","input")))
check("duplicate identity rejected",fails(build_day_endpoints(rep(1,10),base,death,loss,diag,d("2020-12-31"),"censor","prevalent","exclude")))
result <- data.frame(check=names(checks),passed=unlist(checks))
write.csv(result,args[2],row.names=FALSE)
cat(nrow(result),"/",nrow(result),"synthetic policy/mechanics checks passed; no real endpoints rebuilt.\n")
